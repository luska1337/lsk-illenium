function Convert()
    for i = 1, #Config.Stores do
        local store = Config.Stores[i]
        local coords, type, gang, job = store.coords, store.type, store.gang, store.job
        local hasBlip = store.showBlip == true
        local title = "Shop " .. i

        local formatCoords = string.format("[%.2f,%.2f,%.2f,%.2f]", coords.x, coords.y, coords.z, coords.w)

        local groupType, groupName = gang and "gang" or (job and "job"), gang or job
        local formatPermission = groupName and json.encode({ [groupType] = groupName }) or nil

        exports.oxmysql:query_async(
            "INSERT INTO illenium_shops (label, type, coords, blip, groups) VALUES (?, ?, ?, ?, ?)",
            { title, type, formatCoords, hasBlip, formatPermission }
        )
    end

    lib.print.info(locale('CONVERT', #Config.Stores))
end

